GLYPHS = {c: s.split("|") for c, s in _F.items()}
GW, GH = 5, 7


def gw(ch):
    return len(GLYPHS.get(ch, GLYPHS[" "])[0])


def width(text, scale=3, tracking=1):
    t = text.upper()
    if not t:
        return 0
    return (sum(gw(c) for c in t) + tracking * (len(t) - 1)) * scale


def stamp(cov, text, x, y, scale=3, tracking=1, alpha=1.0):
    """Burn `text` into coverage array `cov` with top-left at (x, y)."""
    H, W = cov.shape
    cx = x
    for ch in text.upper():
        g = GLYPHS.get(ch, GLYPHS[" "])
        w = len(g[0])
        for r in range(GH):
            row = g[r]
            for c in range(w):
                if row[c] != "#":
                    continue
                y0, y1 = y + r * scale, y + (r + 1) * scale
                x0, x1 = cx + c * scale, cx + (c + 1) * scale
                if x1 <= 0 or x0 >= W or y1 <= 0 or y0 >= H:
                    continue
                cov[max(0, y0):min(H, y1), max(0, x0):min(W, x1)] = alpha
        cx += (w + tracking) * scale
    return cx
